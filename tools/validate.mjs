#!/usr/bin/env node
// Validate every hand-off file in a project against schemas/ plus editorial rules.
// usage: node tools/validate.mjs <slug>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import { projectGenerator, renderPrompt, sceneSlots, NEGATIVE_RE } from "./lib/prompts.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const slug = process.argv[2];
if (!slug) { console.error("usage: node tools/validate.mjs <slug>"); process.exit(2); }
const P = path.join(ROOT, "projects", slug);
if (!fs.existsSync(P)) { console.error(`projects/${slug} not found`); process.exit(2); }

const ajv = new Ajv2020({ allErrors: true, strict: false });
for (const f of fs.readdirSync(path.join(ROOT, "schemas"))) {
  ajv.addSchema(JSON.parse(fs.readFileSync(path.join(ROOT, "schemas", f), "utf8")));
}

let errors = 0, warnings = 0;
const err = (m) => { errors++; console.log(`  ✗ ${m}`); };
const warn = (m) => { warnings++; console.log(`  ! ${m}`); };
const read = (f) => JSON.parse(fs.readFileSync(f, "utf8"));
const rel = (f) => path.relative(P, f);

function check(file, schemaId) {
  if (!fs.existsSync(file)) return null;
  let data;
  try { data = read(file); } catch (e) { err(`${rel(file)}: invalid JSON (${e.message})`); return null; }
  const v = ajv.getSchema(schemaId);
  if (v(data)) console.log(`  ✓ ${rel(file)}`);
  else for (const e of v.errors) {
    if (e.keyword === "if") continue; // the specific failing rule is reported separately
    err(`${rel(file)} ${e.instancePath || "/"} ${e.message}`);
  }
  return data;
}

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
// Reading time for on-screen text: (characters / 12) + 0.5 seconds, after the entrance.
const readingS = (chars) => chars / 12 + 0.5;

console.log(`Validating projects/${slug}`);
const vision = check(path.join(P, "01_vision/vision-board.json"), "vision-board.schema.json");
const bd = check(path.join(P, "02_breakdown/breakdown.json"), "breakdown.schema.json");

// Generator profile (templates/prompts/generators.json) — every generator-specific rule below
// comes from it. Projects without a generator in their format lock are Runway projects.
const stateFile = path.join(P, "state.json");
let state = null;
try { state = fs.existsSync(stateFile) ? read(stateFile) : null; } catch { /* reported below */ }
let gen;
try { gen = projectGenerator(state, vision); } catch (e) { err(e.message); gen = projectGenerator(null, null); }
const prof = gen.profile;
const sg = state?.format?.generator, vg = vision?.format?.generator;
if (sg && vg && (sg.name !== vg.name || (sg.model ?? null) !== (vg.model ?? null)))
  err(`generator mismatch: state.json format.generator ${sg.name}/${sg.model} ≠ vision board ${vg.name}/${vg.model}`);
if (sg || vg) console.log(`  i generator ${gen.name} · ${gen.model}${prof.generation === "manual" ? " · prompts only, clips are generated by hand" : ""}`);
const t2vOk = (aspect) => prof.t2v_aspects.includes(aspect);

// VO word file — the timing backbone after stage ② (AGENTS.md rule 16)
const wordsFile = path.join(P, "00_script/vo.words.json");
let words = null;
if (fs.existsSync(wordsFile)) {
  try {
    words = read(wordsFile);
    let prev = -1;
    for (const w of words.words ?? []) {
      if (!(typeof w.start === "number" && typeof w.end === "number") || w.start < prev - 0.001 || w.end < w.start) {
        err(`vo.words.json: bad or non-monotonic timestamp at "${w.w ?? "?"}"`); break;
      }
      prev = w.start;
    }
    if (!Array.isArray(words.words) || words.words.length === 0) err("vo.words.json: empty words array");
    else console.log(`  ✓ 00_script/vo.words.json (${words.words.length} words)`);
  } catch (e) { err(`vo.words.json: invalid JSON (${e.message})`); words = null; }
}

if (bd?.scenes) {
  const scenes = bd.scenes;
  if (!words) warn("00_script/vo.words.json missing — breakdown must be timed on measured words, not wpm estimates");
  // Coverage
  const scriptFile = path.join(P, "00_script/script.md");
  if (fs.existsSync(scriptFile)) {
    const script = norm(fs.readFileSync(scriptFile, "utf8").replace(/<!--[\s\S]*?-->/g, "").replace(/^#.*$/gm, ""));
    const vo = norm(scenes.map((s) => s.vo_text).join(" "));
    if (script && vo !== script) warn("coverage: concatenated vo_text differs from script.md (headings ignored) — check for missing/extra lines");
  }
  // Ids unique + ordered
  const ids = scenes.map((s) => s.id);
  if (new Set(ids).size !== ids.length) err("breakdown: duplicate scene ids");
  if ([...ids].sort().join() !== ids.join()) warn("breakdown: scene ids are not in timeline order");
  // Totals
  const sum = (t) => scenes.filter((s) => !t || s.type === t).reduce((a, s) => a + s.duration_s, 0);
  const rt = sum(), a = sum("A_ROLL");
  if (Math.abs(rt - bd.totals.runtime_s) > 0.05) err(`totals.runtime_s ${bd.totals.runtime_s} ≠ sum of scenes ${rt}`);
  if (Math.abs(a - bd.totals.a_roll_s) > 0.05) err(`totals.a_roll_s ${bd.totals.a_roll_s} ≠ ${a}`);
  // Rhythm
  const target = vision?.strategy?.a_roll_ratio;
  if (target != null && Math.abs(a / rt - target) > 0.1) warn(`A-roll ratio ${(a / rt).toFixed(2)} is >10 pts from target ${target}`);
  let runB = 0, runA = 0, prevEnd = null;
  for (const s of scenes) {
    if (s.type === "B_ROLL") { runB++; runA = 0; } else { runB = 0; runA = (s.overlays?.length ? 0 : runA + s.duration_s); }
    if (runB > 3) warn(`${s.id}: more than 3 consecutive B-roll scenes`);
    if (runA > 20) warn(`${s.id}: more than 20 s of A-roll without an overlay or cutaway`);
    if (s.type === "A_ROLL" && s.continuity_from === undefined) warn(`${s.id}: continuity_from not set`);
    if (s.type === "A_ROLL" && s.duration_s > prof.duration_s.max) err(`${s.id}: ${s.duration_s}s is longer than a ${gen.name} clip (${prof.duration_s.max}s) — split it`);
    if (s.type === "A_ROLL" && !s.view && gen.name !== "runway") warn(`${s.id}: no view — pick a prompt template (templates/prompts/README.md)`);
    if (s.type !== "A_ROLL" && s.view) warn(`${s.id}: view is only used on A_ROLL scenes`);
    // Measured VO window
    if (s.vo_start_s != null && s.vo_end_s != null) {
      if (s.vo_end_s <= s.vo_start_s) err(`${s.id}: vo_end_s ≤ vo_start_s`);
      if (Math.abs((s.vo_end_s - s.vo_start_s) - s.duration_s) > 1.0)
        warn(`${s.id}: duration_s ${s.duration_s} is >1 s from measured VO window ${(s.vo_end_s - s.vo_start_s).toFixed(2)} s`);
      if (prevEnd != null && s.vo_start_s < prevEnd - 0.001) warn(`${s.id}: VO window overlaps previous scene`);
      prevEnd = s.vo_end_s;
    } else if (words) warn(`${s.id}: vo_start_s/vo_end_s not set — time it from vo.words.json`);
    // Reading time for text carried by b-roll props
    if (s.type === "B_ROLL" && s.broll?.props) {
      const texts = Object.values(s.broll.props).flatMap((v) =>
        typeof v === "string" ? [v] : Array.isArray(v) ? v.filter((x) => typeof x === "string") : []);
      const longest = Math.max(0, ...texts.map((t) => t.length));
      if (longest && s.duration_s < readingS(longest))
        warn(`${s.id}: "${texts.find((t) => t.length === longest).slice(0, 30)}…" needs ${readingS(longest).toFixed(1)} s to read, scene is ${s.duration_s} s`);
    }
  }
  // Aspect the generator can't do as text-to-video needs I2V
  if (vision && !t2vOk(vision.format.aspect_ratio)) console.log(`  i aspect ${vision.format.aspect_ratio}: every A-roll take must be image_to_video (${gen.name})`);
}

const dir = (d, suffix) => fs.existsSync(path.join(P, d))
  ? fs.readdirSync(path.join(P, d)).filter((f) => f.endsWith(suffix)).map((f) => path.join(P, d, f)) : [];

for (const f of dir("03_prompts", ".prompt.json")) {
  const p = check(f, "scene-prompt.schema.json");
  if (!p) continue;
  if (vision && !t2vOk(vision.format.aspect_ratio))
    for (const t of p.takes) if (t.mode !== "image_to_video") err(`${rel(f)} take ${t.take}: ${vision.format.aspect_ratio} project requires image_to_video`);
  if ((p.generator ?? "runway") !== gen.name) err(`${rel(f)}: rendered for ${p.generator ?? "runway"}, project generator is ${gen.name} — re-render (tools/render-prompt.mjs)`);
  const sc = bd?.scenes.find((s) => s.id === p.scene_id);
  if (bd) {
    if (!sc) err(`${rel(f)}: scene ${p.scene_id} not in breakdown`);
    else if (sc.type !== "A_ROLL") err(`${rel(f)}: ${p.scene_id} is not an A_ROLL scene`);
    else for (const t of p.takes) if (t.duration_s < sc.duration_s) err(`${rel(f)} take ${t.take}: duration ${t.duration_s}s shorter than scene ${sc.duration_s}s`);
    if (sc?.view && p.view && sc.view !== p.view) err(`${rel(f)}: view ${p.view} ≠ breakdown view ${sc.view}`);
  }
  for (const t of p.takes) {
    const at = `${rel(f)} take ${t.take}`;
    const { min, max } = prof.duration_s;
    if (t.duration_s < min || t.duration_s > max) err(`${at}: duration ${t.duration_s}s outside ${gen.name} range ${min === max ? `${max}s` : `${min}–${max}s`}`);
    if (!prof.negative_phrasing && NEGATIVE_RE.test(t.prompt)) err(`${at}: uses negative phrasing (no/not/without/avoid/don't/never) — ${gen.name} only follows positive instructions`);
    if (t.prompt.length > prof.prompt_max_chars) err(`${at}: prompt is ${t.prompt.length} chars, ${gen.name} limit ${prof.prompt_max_chars}`);
    if (t.mode === "text_to_video" && !t2vOk(t.aspect_ratio)) err(`${at}: ${gen.name} text-to-video supports ${prof.t2v_aspects.join(", ")} — use image_to_video`);
    if (t.mode === "image_to_video" && !prof.i2v_aspects.includes(t.aspect_ratio)) err(`${at}: ${gen.name} image-to-video supports ${prof.i2v_aspects.join(", ")}`);
    if (t.fps != null && !prof.fps.includes(t.fps)) warn(`${at}: ${gen.name} outputs ${prof.fps.join("/")} fps, take says ${t.fps}`);
    if (prof.first_frame_for_cast && t.mode === "text_to_video" && sc?.cast?.length) warn(`${at}: ${sc.cast.join(", ")} on screen without a first-frame reference — ${gen.name} needs one for consistency`);
    if (t.mode === "image_to_video" && t.generated_at == null && !fs.existsSync(path.join(P, t.keyframe)) && !(p.keyframe_prompt?.output_path === t.keyframe))
      warn(`${at}: first frame ${t.keyframe} not found`);
    // Takes rendered from a template must still match it (catches hand edits and stale renders)
    if (t.slots && vision) {
      try {
        const r = renderPrompt({ view: p.view, generator: gen, slots: sceneSlots(sc, t.slots), vision, duration_s: t.duration_s, aspect: t.aspect_ratio });
        if (r.text !== t.prompt) warn(`${at}: prompt differs from its template render — re-run tools/render-prompt.mjs ${slug} ${p.scene_id} --take ${t.take}`);
        for (const w of r.warnings) warn(`${at}: ${w}`);
      } catch (e) { err(`${at}: template render failed — ${e.message}`); }
    }
  }
  if (prof.generation === "manual") {
    const md = f.replace(/\.json$/, ".md");
    const last = p.takes[p.takes.length - 1];
    if (!fs.existsSync(md)) warn(`${rel(f)}: ${rel(md)} missing — the copy-paste prompt for manual generation (tools/render-prompt.mjs)`);
    else if (!fs.readFileSync(md, "utf8").includes(last.prompt)) warn(`${rel(md)} is stale: it does not contain take ${last.take}'s prompt`);
  }
}

for (const f of dir("05_review", ".review.json")) {
  const r = check(f, "clip-review.schema.json");
  const sc = bd?.scenes.find((s) => s.id === r?.scene_id);
  for (const rv of r?.reviews ?? []) {
    if (rv.in_s != null && rv.out_s != null) {
      if (rv.out_s <= rv.in_s) err(`${rel(f)} take ${rv.take}: out_s ≤ in_s`);
      if (rv.out_s > rv.probe.duration_s + 0.05) err(`${rel(f)} take ${rv.take}: out_s beyond clip length`);
      if (sc && rv.out_s - rv.in_s + 0.05 < sc.duration_s) err(`${rel(f)} take ${rv.take}: usable range shorter than scene duration`);
    }
    if (rv.decision === "stitch") {
      let cover = 0;
      for (const seg of rv.stitch ?? []) {
        if (seg.out_s <= seg.in_s) err(`${rel(f)} stitch take ${seg.take}: out_s ≤ in_s`);
        cover += Math.max(0, seg.out_s - seg.in_s);
      }
      if (sc && cover + 0.05 < sc.duration_s) err(`${rel(f)}: stitch covers ${cover.toFixed(2)} s, scene needs ${sc.duration_s} s`);
    }
    if (rv.chain_frame_s != null && rv.out_s != null && rv.chain_frame_s > rv.out_s)
      warn(`${rel(f)} take ${rv.take}: chain_frame_s ${rv.chain_frame_s} is past out_s — chain from momentum inside the usable range, never the settled tail`);
    if (!fs.existsSync(path.join(P, rv.clip))) warn(`${rel(f)} take ${rv.take}: clip ${rv.clip} not found`);
  }
}

const design = check(path.join(P, "05_broll/broll-design.json"), "broll-design.schema.json");
if (design && bd) {
  for (const card of design.cards ?? []) {
    const sc = bd.scenes.find((s) => s.id === card.scene_id);
    if (!sc) err(`broll-design: ${card.scene_id} not in breakdown`);
    else if (sc.type !== "B_ROLL" && sc.status !== "fallback") warn(`broll-design: ${card.scene_id} is not a B_ROLL/fallback scene`);
  }
}

const edl = check(path.join(P, "06_edit/edl.json"), "edl.schema.json");
if (edl) {
  const pub = path.join(ROOT, "remotion/public");
  for (const s of edl.segments) {
    if (s.kind === "clip" && !fs.existsSync(path.join(pub, s.src))) warn(`edl ${s.scene_id}: ${s.src} not in remotion/public (run tools/sync-media.sh ${slug})`);
    for (const o of s.overlays ?? []) if (o.to_s > s.duration_s + 0.01 || o.from_s >= o.to_s) err(`edl ${s.scene_id}: overlay ${o.template} timing outside segment`);
  }
  for (const a of edl.audio ?? []) if (!fs.existsSync(path.join(pub, a.src))) warn(`edl audio ${a.src} not in remotion/public`);
  const total = edl.segments.reduce((t, s) => t + s.duration_s, 0);
  console.log(`  i EDL runtime ${total.toFixed(2)} s, ${edl.segments.length} segments`);
  if (edl.segments.some((s) => s.kind === "broll") && !design)
    warn("edl has b-roll segments but 05_broll/broll-design.json is missing — b-roll must be designed against the VO words (stage ⑥)");
}

// ---------- storyboard flow (docs/flow-storyboard.md) ----------
const flowState = fs.existsSync(stateFile) ? (() => { try { return read(stateFile); } catch { return null; } })() : null;
if (flowState?.flow === "storyboard") {
  const sbFile = path.join(P, "02_storyboard/storyboard.json");
  const sb = check(sbFile, "storyboard.schema.json");
  const order = ["storyboard", "generate", "ingest", "scenes", "edit", "render", "done"];
  if (!order.includes(flowState.stage)) err(`state.json: unknown storyboard-flow stage "${flowState.stage}" (expected ${order.join("|")})`);
  const atLeast = (st) => order.indexOf(flowState.stage) >= order.indexOf(st);
  const ex = (f) => fs.existsSync(path.join(P, f));
  const nw = (w) => w.toLowerCase().replace(/[’']/g, "").replace(/[^a-z0-9]+/g, "");
  if (sb) {
    const ids = sb.clips.map((c) => c.id);
    if (new Set(ids).size !== ids.length) err("storyboard: duplicate clip ids");
    const names = new Map();
    for (const c of sb.clips) {
      const words = c.line.split(/\s+/).map(nw);
      const budget = (gen.profile.duration_s?.max ?? 8) - 0.6;
      if (words.length / 2.7 > budget) warn(`storyboard ${c.id}: ${words.length} words ≈ ${(words.length / 2.7).toFixed(1)} s of speech, budget ${budget.toFixed(1)} s — split the line`);
      const refs = [...(c.edit?.host ?? []).map((h) => h[0]), ...(c.edit?.scenes ?? []).flatMap((x) => Object.values(x.cues ?? {}))];
      for (const r of refs) {
        if (typeof r !== "string" || r.startsWith("@")) continue;
        const key = r.replace(/(#\d+)?([+-]\d*\.?\d+)?$/, "");
        if (!words.includes(nw(key))) err(`storyboard ${c.id}: cue "${r}" — "${key}" is not in the line`);
      }
      for (const x of c.edit?.scenes ?? []) {
        if (names.has(x.name) && names.get(x.name) !== x.layer) warn(`storyboard: scene ${x.name} used on different layers`);
        names.set(x.name, x.layer);
        if (!x.idea && x.name !== "LogoBug") warn(`storyboard ${c.id}: scene ${x.name} has no idea — the scene-builder needs one`);
      }
      const modes = (c.edit?.host ?? []).map((h) => h[1]);
      if (!modes.length) warn(`storyboard ${c.id}: no host keyframes (defaults to full)`);
    }
    for (let i = 1; i < sb.clips.length; i++) {
      const sig = (c) => `${(c.edit?.host ?? []).map((h) => h[1]).join(">")}|${(c.edit?.scenes ?? []).map((x) => x.layer).join(",")}`;
      if (sig(sb.clips[i]) === sig(sb.clips[i - 1])) warn(`storyboard ${sb.clips[i].id}: same layout and scene layers as ${sb.clips[i - 1].id} — vary adjacent beats`);
    }
    if (!ex("02_storyboard/storyboard.md")) warn("02_storyboard/storyboard.md missing — the user approves the storyboard from it");
    for (const c of sb.clips) if (!ex(`03_prompts/clip-${c.id}.prompt.md`)) warn(`03_prompts/clip-${c.id}.prompt.md missing — run tools/storyboard-prompts.mjs ${slug}`);
    if (atLeast("scenes") || ex("05_ingest/ingest.json")) {
      if (!ex("05_ingest/ingest.json")) err(`stage "${flowState.stage}" but 05_ingest/ingest.json is missing — run tools/ingest.py ${slug}`);
      else {
        const ing = read(path.join(P, "05_ingest/ingest.json"));
        for (const m of ing.missing ?? []) err(`ingest: clip ${m} has no take`);
        for (const c of ing.clips ?? []) if (c.similarity < 0.8) warn(`ingest ${c.id}: take ${c.take} similarity ${c.similarity} — check it says the line`);
      }
    }
    const sceneDir = path.join(ROOT, "remotion/src/projects", slug);
    if (atLeast("edit") || fs.existsSync(sceneDir)) {
      const builtIn = new Set(["LogoBug"]);
      for (const [n] of names) if (!builtIn.has(n) && !fs.existsSync(path.join(sceneDir, `${n}.tsx`))) err(`scene ${n}: remotion/src/projects/${slug}/${n}.tsx missing`);
      const idx = path.join(ROOT, "remotion/src/projects/index.ts");
      if (fs.existsSync(sceneDir) && !(fs.existsSync(idx) && fs.readFileSync(idx, "utf8").includes(`"${slug}"`))) err(`scenes for ${slug} not registered — run tools/register-scenes.mjs`);
    }
    if (atLeast("render") && !ex("06_edit/timeline.json")) err(`stage "${flowState.stage}" but 06_edit/timeline.json is missing`);
    const renders = ex("renders") && fs.readdirSync(path.join(P, "renders")).some((f) => f.endsWith(".mp4"));
    if (renders && !atLeast("render")) err(`state.json stage "${flowState.stage}" is stale: renders exist`);
    if (atLeast("generate") && !flowState.approved?.storyboard) err(`stage "${flowState.stage}" but approved.storyboard is false — the storyboard gate was skipped`);
  } else if (atLeast("generate")) err(`stage "${flowState.stage}" but 02_storyboard/storyboard.json is missing`);
}

// Stage vs artifacts — a stale state.json resumes the pipeline in the wrong place,
// and the validator must tell "not reached yet" apart from "skipped".
if (fs.existsSync(stateFile) && flowState?.flow !== "storyboard") {
  try {
    const st = read(stateFile);
    const order = ["audit", "vision", "breakdown", "prompting", "review", "broll", "assembly", "done"];
    if (!order.includes(st.stage)) warn(`state.json: unknown stage "${st.stage}" (expected one of ${order.join("|")})`);
    const atLeast = (s) => order.indexOf(st.stage) >= order.indexOf(s);
    const renders = fs.existsSync(path.join(P, "renders")) && fs.readdirSync(path.join(P, "renders")).some((f) => f.endsWith(".mp4"));
    if ((renders || edl) && !atLeast("assembly"))
      err(`state.json stage "${st.stage}" is stale: ${renders ? "renders" : "06_edit/edl.json"} already exist (rule 8)`);
    else if (design && !atLeast("broll")) warn(`state.json stage "${st.stage}" is stale: broll-design.json exists`);
    else if (bd && !atLeast("breakdown")) warn(`state.json stage "${st.stage}" is stale: breakdown.json exists`);
    else if (vision && !atLeast("vision")) warn(`state.json stage "${st.stage}" is stale: vision-board.json exists`);
    if (atLeast("breakdown") && st.stage !== "done" && !words)
      warn(`state.json stage "${st.stage}" but vo.words.json is missing — the VO lock (stage ②) was skipped`);
  } catch (e) { err(`state.json: invalid JSON (${e.message})`); }
}

console.log(`\n${errors} error(s), ${warnings} warning(s)`);
process.exit(errors ? 1 : 0);
