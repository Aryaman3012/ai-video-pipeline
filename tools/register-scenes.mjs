#!/usr/bin/env node
// Regenerate remotion/src/projects/index.ts from every remotion/src/projects/<slug>/index.tsx.
// Each project folder exports `SCENES: Record<string, React.FC<any>>`.
// usage: node tools/register-scenes.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(ROOT, "remotion/src/projects");
const slugs = fs.readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, "index.tsx")))
  .map((d) => d.name)
  .sort();
const id = (s) => "p_" + s.replace(/[^a-zA-Z0-9]/g, "_");
const out = [
  "// GENERATED by tools/register-scenes.mjs — do not edit. Maps a project slug to its scene components.",
  'import type React from "react";',
  ...slugs.map((s) => `import { SCENES as ${id(s)} } from "./${s}";`),
  "export const PROJECT_SCENES: Record<string, Record<string, React.FC<any>>> = { // eslint-disable-line @typescript-eslint/no-explicit-any",
  ...slugs.map((s) => `  ${JSON.stringify(s)}: ${id(s)},`),
  "};",
  "",
].join("\n");
fs.writeFileSync(path.join(dir, "index.ts"), out);
console.log(`registered scenes for: ${slugs.join(", ") || "(none)"}`);
